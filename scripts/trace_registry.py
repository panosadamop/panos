"""Build or verify the requirement registry from the specification pack.

Usage:
    python scripts/trace_registry.py          # regenerate docs/traceability/requirements.yaml
    python scripts/trace_registry.py --check  # fail if the registry is stale or IDs are invalid

The registry is derived from docs/specs (BRD, FRD, NFR, USER_STORIES, ACCEPTANCE_CRITERIA)
so it cannot drift from the specs. Standard library only.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPECS = ROOT / "docs" / "specs"
REGISTRY = ROOT / "docs" / "traceability" / "requirements.yaml"


@dataclass(frozen=True)
class Requirement:
    id: str
    type: str
    title: str
    source: str
    parent: str | None = None


HEADING_RE = re.compile(r"^## ((?:BR|FR)-\d{3}) (.+)$")
NFR_RE = re.compile(r"^- (NFR-[A-Z]+-\d{3}) (.+)$")
EPIC_RE = re.compile(r"^## (EPIC-\d{3}) (.+)$")
US_RE = re.compile(r"^- (US-\d{3}) (.+)$")
AC_RE = re.compile(r"^- (AC-US\d{3}-\d{2}) (.+)$")
AC_GROUP_RE = re.compile(r"^## AC-(US\d{3})\b")


def _clean(text: str) -> str:
    text = re.sub(r"\*\((?:new|BR|FR|NFR)[^)]*\)\*", "", text)
    text = text.replace("*(new)*", "")
    return " ".join(text.split()).strip()


def parse() -> list[Requirement]:
    reqs: list[Requirement] = []
    for fname in ("BRD.md", "FRD.md"):
        for line in (SPECS / fname).read_text(encoding="utf-8").splitlines():
            if m := HEADING_RE.match(line):
                reqs.append(Requirement(m[1], m[1][:2], _clean(m[2]), fname))
    for line in (SPECS / "NFR.md").read_text(encoding="utf-8").splitlines():
        if m := NFR_RE.match(line):
            reqs.append(Requirement(m[1], "NFR", _clean(m[2]), "NFR.md"))
    epic: str | None = None
    for line in (SPECS / "USER_STORIES.md").read_text(encoding="utf-8").splitlines():
        if m := EPIC_RE.match(line):
            epic = m[1]
            reqs.append(Requirement(m[1], "EPIC", _clean(m[2]), "USER_STORIES.md"))
        elif m := US_RE.match(line):
            reqs.append(Requirement(m[1], "US", _clean(m[2]), "USER_STORIES.md", epic))
    group: str | None = None
    for line in (SPECS / "ACCEPTANCE_CRITERIA.md").read_text(encoding="utf-8").splitlines():
        if m := AC_GROUP_RE.match(line):
            group = m[1].replace("US", "US-")
        elif m := AC_RE.match(line):
            reqs.append(Requirement(m[1], "AC", _clean(m[2]), "ACCEPTANCE_CRITERIA.md", group))
    return reqs


def validate(reqs: list[Requirement]) -> list[str]:
    errors: list[str] = []
    seen: set[str] = set()
    for r in reqs:
        if r.id in seen:
            errors.append(f"duplicate id {r.id}")
        seen.add(r.id)
    for r in reqs:
        if r.type == "AC":
            story = "US-" + r.id[5:8]
            if r.parent != story:
                errors.append(f"{r.id} is listed under {r.parent}, expected {story}")
            if story not in seen:
                errors.append(f"{r.id} references unknown story {story}")
        if r.type == "US" and r.parent is None:
            errors.append(f"{r.id} has no epic")
    return errors


def _yaml_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(reqs: list[Requirement]) -> str:
    out = [
        "# GENERATED by scripts/trace_registry.py from docs/specs. Do not edit by hand.",
        f"count: {len(reqs)}",
        "requirements:",
    ]
    for r in reqs:
        out.append(f"  - id: {r.id}")
        out.append(f"    type: {r.type}")
        out.append(f"    title: {_yaml_str(r.title)}")
        out.append(f"    source: docs/specs/{r.source}")
        if r.parent:
            out.append(f"    parent: {r.parent}")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify instead of writing")
    args = parser.parse_args()

    reqs = parse()
    errors = validate(reqs)
    for e in errors:
        print(f"ERROR: {e}", file=sys.stderr)
    if errors:
        return 1

    content = render(reqs)
    if args.check:
        current = REGISTRY.read_text(encoding="utf-8") if REGISTRY.exists() else ""
        if current != content:
            print(
                "ERROR: requirements.yaml is stale; run scripts/trace_registry.py", file=sys.stderr
            )
            return 1
        print(f"OK: {len(reqs)} requirements, registry up to date")
        return 0

    REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    REGISTRY.write_text(content, encoding="utf-8", newline="\n")
    counts: dict[str, int] = {}
    for r in reqs:
        counts[r.type] = counts.get(r.type, 0) + 1
    print(
        f"wrote {REGISTRY.relative_to(ROOT)}: " + ", ".join(f"{k}={v}" for k, v in counts.items())
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
