"""Markdown → Word (.docx) with python-docx (FR-029, BR-028)."""

import io

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor
from docx.text.paragraph import Paragraph as DocxParagraph

from panos_core.documents.markdown import (
    Code,
    Heading,
    ListBlock,
    Paragraph,
    Quote,
    Rule,
    Table,
    parse,
    plain,
    runs,
)

CODE_FONT = "Consolas"


def _add_runs(paragraph: DocxParagraph, text: str) -> None:
    for r in runs(text):
        run = paragraph.add_run(r.text)
        run.bold = r.bold or None
        run.italic = r.italic or None
        if r.code:
            run.font.name = CODE_FONT


def render_docx(markdown: str, *, title: str, author: str = "Panos") -> bytes:
    doc = Document()
    props = doc.core_properties
    props.title = title
    props.author = author
    props.comments = "Generated by Panos."
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(10.5)

    titles = 0
    for block in parse(markdown):
        if isinstance(block, Heading):
            # Level 1 is a document title (each starts a new page); deeper headings shift up.
            if block.level == 1:
                if titles:
                    doc.add_page_break()
                titles += 1
                doc.add_heading(plain(block.text), level=0)
            else:
                doc.add_heading(plain(block.text), level=min(block.level - 1, 9))
        elif isinstance(block, Paragraph):
            _add_runs(doc.add_paragraph(), block.text)
        elif isinstance(block, Quote):
            p = doc.add_paragraph(style="Quote")
            _add_runs(p, block.text)
        elif isinstance(block, ListBlock):
            for item in block.items:
                base = "List Number" if item.ordered else "List Bullet"
                level = min(item.depth, 2)
                p = doc.add_paragraph(style=base if level == 0 else f"{base} {level + 1}")
                _add_runs(p, item.text)
        elif isinstance(block, Table):
            table = doc.add_table(rows=1, cols=len(block.header))
            table.style = "Light Grid Accent 1"
            for cell, text in zip(table.rows[0].cells, block.header, strict=True):
                cell.text = ""
                run = cell.paragraphs[0].add_run(plain(text))
                run.bold = True
            for row in block.rows:
                cells = table.add_row().cells
                for cell, text in zip(cells, row, strict=True):
                    cell.text = ""
                    _add_runs(cell.paragraphs[0], text)
            doc.add_paragraph()
        elif isinstance(block, Code):
            if block.language == "mermaid":
                note = doc.add_paragraph()
                note.add_run("Diagram (Mermaid source):").italic = True
            p = doc.add_paragraph()
            run = p.add_run(block.text)
            run.font.name = CODE_FONT
            run.font.size = Pt(9)
            run.font.color.rgb = RGBColor(0x33, 0x33, 0x33)
        elif isinstance(block, Rule):
            p = doc.add_paragraph("―" * 20)
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER

    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()
